# 1. How do you calculate your net worth given your assets and debts?

saving_account = 15000
checking_account = 10000
stocks_value = 100000

total_assets = saving_account + checking_account + stocks_value


student_loan = 12000
credit_card_debt = 5000
medical_debt = 8000

total_debts = student_loan + credit_card_debt + medical_debt 


net_worth = total_assets - total_debts


print("Your total assets are $" + str(total_assets))
print("Your total debts are $" + str(total_debts))
print("Your net worth is $" + str(net_worth))


